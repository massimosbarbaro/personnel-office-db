INSERT INTO Contributi ( COGNOME, NOME, [CODICE FISCALE], Militare, MarcheExtra, DataContributi, Contributi )
SELECT FICHA11.COGNOME, FICHA11.NOME, FICHA11.[CODICE FISCALE], "" AS Militare, "" AS MarcheExtra, IIf([DATA ASSUNZIONE]>[DATA ASSUNZIONE GRUPPO],[DATA ASSUNZIONE GRUPPO],[DATA ASSUNZIONE]) AS DataContributi, DateDiff("ww",[Datacontributi],Date()) AS Contributi
FROM FICHA11
ORDER BY IIf([DATA ASSUNZIONE]>[DATA ASSUNZIONE GRUPPO],[DATA ASSUNZIONE GRUPPO],[DATA ASSUNZIONE]);
